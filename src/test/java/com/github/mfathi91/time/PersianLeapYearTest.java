    @Test
    public void testOnIsLeapYearInNext200Years() {
        for (int year = FIRST_YEAR; year <= LAST_YEAR; year++) {
            assertEquals("year " + year, LEAP_YEARS.contains(year), PersianDate.isLeapYear(year));
            assertEquals("year " + year, LEAP_YEARS.contains(year), PersianChronology.INSTANCE.isLeapYear(year));
            assertEquals("year " + year, LEAP_YEARS.contains(year) ? 366 : 365, PersianDate.of(year, 1, 1).lengthOfYear());
        }
    }

    @Test
    public void testOnLeapYearBoundariesInNext200Years() {
        assertEquals(LEAP_YEARS.size(), LEAP_YEAR_BOUNDARIES.length);
        for (int i = 0; i < LEAP_YEAR_BOUNDARIES.length; i++) {
            final String[] row = LEAP_YEAR_BOUNDARIES[i];
            final int leapYear = Integer.parseInt(row[0]);
            assertEquals((int) LEAP_YEARS.get(i), leapYear);
            assertYear(leapYear - 1, LocalDate.parse(row[1]), LocalDate.parse(row[2]), false);
            assertYear(leapYear, LocalDate.parse(row[3]), LocalDate.parse(row[4]), true);
            assertYear(leapYear + 1, LocalDate.parse(row[5]), LocalDate.parse(row[6]), false);
        }
    }

    private static void assertYear(int year, LocalDate firstDay, LocalDate lastDay, boolean leapYear) {
        final String message = "year " + year;
        final PersianDate first = PersianDate.of(year, 1, 1);
        final PersianDate last = PersianDate.of(year, 12, leapYear ? 30 : 29);

        assertEquals(message, leapYear, PersianDate.isLeapYear(year));
        assertEquals(message, firstDay, first.toGregorian());
        assertEquals(message, lastDay, last.toGregorian());
        assertEquals(message, first, PersianDate.fromGregorian(firstDay));
        assertEquals(message, last, PersianDate.fromGregorian(lastDay));
        assertEquals(message, PersianDate.of(year - 1, 12, PersianDate.isLeapYear(year - 1) ? 30 : 29),
                PersianDate.fromGregorian(firstDay.minusDays(1)));
        assertEquals(message, PersianDate.of(year + 1, 1, 1), PersianDate.fromGregorian(lastDay.plusDays(1)));
        assertEquals(message, leapYear ? 366 : 365, lastDay.toEpochDay() - firstDay.toEpochDay() + 1);
        if (!leapYear) {
            try {
                PersianDate.of(year, 12, 30);
                fail(message + " is not a leap year, so Esfand 30th must be invalid");
            } catch (DateTimeException expected) {
                // expected
            }
        }
    }
